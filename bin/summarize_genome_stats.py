#!/usr/bin/env python

import argparse
import logging
import sys
from pathlib import Path
from typing import Dict, Union
import pandas as pd
import yaml

def summarize_genome_stat(genome_stat_file):
    """ """

    df = pd.read_csv(
        genome_stat_file,
        sep="\t",
        comment="#",
    )

    df["Persistent_families_fraction"] = df["Persistent_families"] / df["Families"]
    df["Soft_core_families_fraction"] = df["Soft_core_families"] / df["Families"]
    df["Exact_core_families_fraction"] = df["Exact_core_families"] / df["Families"]

    df["Shell_families_fraction"] = df["Shell_families"] / df["Families"]
    df["Cloud_families_fraction"] = df["Cloud_families"] / df["Families"]

    # df["Variable_families"] = df["Shell_families"] + df["Cloud_families"]

    # df["Variable_families_fraction"] = df["Variable_families"] / df["Families"]

    columns_to_process = [
        "Persistent_families",
        "Soft_core_families",
        "Exact_core_families",
        "Shell_families",
        "Cloud_families",
        "Persistent_families_fraction",
        "Soft_core_families_fraction",
        "Exact_core_families_fraction",
        "Shell_families_fraction",
        "Cloud_families_fraction",
        "Fragmentation",
        "Completeness",
        "Contamination",
        "Genes",
        "Contigs",
        "Families",
    ]

    species_stats: Dict[str, Dict[str, Union[float, int]]] = {}

    # Calculate stats for each column
    for column in columns_to_process:
        if column in df.columns:
            stats = df[column].agg(["min", "max", "mean", "median", "std"]).to_dict()
            species_stats[column] = stats
            # stats["Q1"] = df[column].quantile(0.25)
            # stats["Q3"] = df[column].quantile(0.75)

            # # Compute IQR
            # stats["IQR"] = stats["Q3"] - stats["Q1"]

    return species_stats

def dump_dict_to_yaml(data, filename):
    """
    Dumps a nested dictionary (double dictionary) into a YAML-formatted file
    using the yaml module.

    :param data: The nested dictionary to dump.
    :param filename: The name of the file to write to.
    """
    with open(filename, "w") as file:
        yaml.dump(data, file, default_flow_style=False, sort_keys=False)


def parse_args(argv=None):
    """Define and immediately parse command line arguments."""
    parser = argparse.ArgumentParser(
        description="Parse genome paths and taxonomy.",
        epilog="Example: python gather_pangenome_infos.py --yaml_dir <yaml_info_dir>",
    )
    parser.add_argument(
        "--genome_stats",
        help="TSV file with genome statistics generated by ppanggolin.",
        required=True,
        type=Path,
    )
    parser.add_argument(
        "-o",
        "--output",
        help="Output file containing genome stats summarized in YAML format.",
        default="genome_stats_summary.yaml",
        type=Path,
    )

    parser.add_argument(
        "-l",
        "--log-level",
        help="Desired log level (default: WARNING).",
        choices=("CRITICAL", "ERROR", "WARNING", "INFO", "DEBUG"),
        default="INFO",
    )

    args = parser.parse_args(argv)

    return args


def main(argv=None):
    """Coordinate argument parsing and program execution."""
    args = parse_args(argv)

    logging.basicConfig(level=args.log_level, format="[%(levelname)s] %(message)s")

    genome_stats_summary = summarize_genome_stat(args.genome_stats)
    dump_dict_to_yaml(genome_stats_summary, args.output)


if __name__ == "__main__":
    sys.exit(main())
